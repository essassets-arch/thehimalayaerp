function parseProducts() {
  const lines = rawInput.split('\n').map(l => l.trim()).filter(Boolean);
  const items = [];
  for (const line of lines) {
    const parts = line.split('\t').map(p => p.trim()).filter(Boolean);
    let rawName = parts[0] || line;
    let cleanName = rawName.replace(/\s+/g, ' ').replace(/\bBLACJK\b/g, 'BLACK');
    const match = cleanName.match(/HIMALAYA\s+FRP\s+MHC\s+([0-9]+X[0-9]+)\s+(ELD|LD)\s+([A-Z]+)/i);
    if (!match) continue;

    const size = match[1].toUpperCase();
    const capacity = match[2].toUpperCase();
    const color = match[3].toUpperCase();
    const sku = cleanName.replace(/[^a-zA-Z0-9]/g, '').toUpperCase().substring(0, 50);

    items.push({
      name: cleanName,
      sku: sku,
      brand: 'HIMALAYA',
      category: 'FRP COVERS',
      productType: 'MANUFACTURING',
      dispatchCategory: 'D1',
      unit: 'SET',
      unitPrice: 0,
      gstRate: 18,
      hsnCode: '39259090',
      size: size,
      type: 'MHC',
      capacity: capacity,
      variantDetails: `MHC ${size} ${capacity} ${color}`,
      description: cleanName,
      coversPerSet: 1,
      framesPerSet: 1,
      minimumStock: 0,
      isActive: true
    });
  }
  return items;
}

async function syncToCloud() {
  console.log('====================================================');
  console.log('🚀 SYNCING 100 INCH MANUFACTURING PRODUCTS TO CLOUD');
  console.log('   Target: https://thehimalaya.cloud/plant-head/products');
  console.log('====================================================');

  // 1. Authenticate with cloud
  const loginRes = await fetch('https://thehimalaya.cloud/api/v1/auth/login', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ email: 'super.admin@himalayaerp.com', password: 'SuperAdmin@hcppl' })
  });

  const authData = await loginRes.json();
  const token = authData.data?.accessToken;
  if (!token) {
    throw new Error('Failed to log in to https://thehimalaya.cloud: ' + JSON.stringify(authData));
  }
  console.log('✓ Successfully authenticated as Super Admin on cloud.');

  const headers = {
    'Authorization': 'Bearer ' + token,
    'Content-Type': 'application/json'
  };

  // 2. Fetch existing products from cloud
  const existingRes = await fetch('https://thehimalaya.cloud/api/v1/products?scope=catalog&limit=5000', { headers });
  const existingData = await existingRes.json();
  const existingList = existingData.data || [];
  const existingSkus = new Set(existingList.map(p => p.sku?.toUpperCase()));
  const existingNames = new Set(existingList.map(p => p.name?.toUpperCase()));

  console.log(`✓ Retrieved ${existingList.length} existing catalog products from cloud.`);

  // 3. Filter items that need to be created
  const allItems = parseProducts();
  console.log(`✓ Parsed ${allItems.length} manufacturing products from user list.`);

  const toCreate = allItems.filter(p => !existingSkus.has(p.sku.toUpperCase()) && !existingNames.has(p.name.toUpperCase()));
  console.log(`✓ Products already on cloud: ${allItems.length - toCreate.length}`);
  console.log(`✓ Products to create:       ${toCreate.length}`);

  if (toCreate.length > 0) {
    // 4. Bulk create items via POST /api/v1/products/bulk
    const bulkRes = await fetch('https://thehimalaya.cloud/api/v1/products/bulk', {
      method: 'POST',
      headers,
      body: JSON.stringify({ items: toCreate })
    });

    const bulkResult = await bulkRes.json();
    if (!bulkRes.ok) {
      console.error('❌ Bulk creation failed:', bulkResult);
      throw new Error(`Bulk create API returned status ${bulkRes.status}`);
    }
    console.log(`✓ Bulk create response:`, bulkResult);
  }

  // 5. Verification
  console.log('\nVerifying newly added products on cloud...');
  const verifyRes = await fetch('https://thehimalaya.cloud/api/v1/products?scope=catalog&limit=5000', { headers });
  const verifyData = await verifyRes.json();
  const verifyList = verifyData.data || [];

  const checkSizes = ['10X10', '12X12', '15X15', '18X18', '18X24', '21X21', '24X24', '28X28', '30X30', '36X36'];
  let totalFound = 0;
  console.log('\nSize Breakdown of Created Inch Manufacturing Products:');
  for (const s of checkSizes) {
    const matching = verifyList.filter(p => p.name.includes(`MHC ${s}`) && p.productType === 'MANUFACTURING');
    console.log(` - Size ${s.padEnd(7)}: ${matching.length} products (5 ELD + 5 LD)`);
    totalFound += matching.length;
  }

  const mfgTotal = verifyList.filter(p => p.productType === 'MANUFACTURING').length;
  const d1Total = verifyList.filter(p => p.dispatchCategory === 'D1').length;

  console.log('\n====================================================');
  console.log(`🎉 VERIFICATION COMPLETE!`);
  console.log(`   - Verified Inch Products on Cloud: ${totalFound} / 100`);
  console.log(`   - Total Manufacturing Products:    ${mfgTotal}`);
  console.log(`   - Total D1 Dispatch Products:      ${d1Total}`);
  console.log(`   - Accessible on: https://thehimalaya.cloud/plant-head/products`);
  console.log('====================================================');
}

syncToCloud().catch(err => {
  console.error('Fatal Error:', err);
  process.exit(1);
});

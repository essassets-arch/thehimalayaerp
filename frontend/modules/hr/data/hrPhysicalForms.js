export function printDocumentHtml(title, bodyHtml) {
  if (typeof window === 'undefined') return;

  try {
    const existing = document.getElementById('hr-print-frame');
    if (existing && document.body.contains(existing)) {
      document.body.removeChild(existing);
    }

    const iframe = document.createElement('iframe');
    iframe.id = 'hr-print-frame';
    iframe.style.position = 'fixed';
    iframe.style.right = '0';
    iframe.style.bottom = '0';
    iframe.style.width = '0';
    iframe.style.height = '0';
    iframe.style.border = '0';
    iframe.style.zIndex = '-9999';
    document.body.appendChild(iframe);

    const doc = iframe.contentWindow.document;
    doc.open();
    doc.write(`<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>${title}</title>
  <style>
    ${PRINT_BASE_CSS}
  </style>
</head>
<body>
  <div class="doc-container">
    ${bodyHtml}
  </div>
</body>
</html>`);
    doc.close();

    setTimeout(() => {
      try {
        iframe.contentWindow.focus();
        iframe.contentWindow.print();
      } catch (err) {
        console.error('Iframe print error:', err);
        window.print();
      }
      setTimeout(() => {
        try {
          if (document.body.contains(iframe)) {
            document.body.removeChild(iframe);
          }
        } catch (e) {}
      }, 5000);
    }, 400);
  } catch (err) {
    console.error('Print trigger failed:', err);
    window.print();
  }
}

/**
 * Enterprise High-Quality PDF Downloader
 * Uses html2pdf with high-resolution canvas scaling (scale: 2 = ~200 DPI vector-crisp)
 */
export async function downloadPDFFromHtml(filename, title, bodyHtml) {
  if (typeof window === 'undefined') return;

  const cleanFilename = filename.endsWith('.pdf') ? filename : `${filename}.pdf`;

  // Create isolated offscreen container with exact A4 96dpi pixel width (794px)
  const container = document.createElement('div');
  container.id = 'hr-pdf-capture-sheet';
  container.style.position = 'fixed';
  container.style.top = '0';
  container.style.left = '0';
  container.style.width = '794px';
  container.style.zIndex = '-9999';
  container.style.background = '#ffffff';
  container.style.color = '#0f172a';
  container.style.padding = '0';
  container.style.margin = '0';
  container.style.boxSizing = 'border-box';
  container.innerHTML = `
    <style>
      ${PRINT_BASE_CSS}
    </style>
    <div class="doc-container" style="width:760px; max-width:760px; margin:0 auto; padding:0; background:#ffffff;">
      ${bodyHtml}
    </div>
  `;

  document.body.appendChild(container);

  try {
    const libs = await getPdfLibs();

    if (libs?.jsPDF && libs?.html2canvas) {
      const { jsPDF, html2canvas } = libs;
      const canvas = await html2canvas(container, {
        scale: 2, // High resolution crisp output (~200 DPI)
        useCORS: true,
        logging: false,
        backgroundColor: '#ffffff',
        windowWidth: 1024,
        scrollX: 0,
        scrollY: 0
      });

      if (document.body.contains(container)) {
        document.body.removeChild(container);
      }

      const pdf = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4'
      });

      const pageWidth = pdf.internal.pageSize.getWidth(); // 210mm
      const pageHeight = pdf.internal.pageSize.getHeight(); // 297mm
      const marginX = 8;
      const marginY = 6;
      const contentWidth = pageWidth - (marginX * 2); // 194mm
      const contentHeight = (canvas.height * contentWidth) / canvas.width;

      const imgData = canvas.toDataURL('image/jpeg', 0.98);

      // Strict 1-Page A4 Guarantee
      if (contentHeight <= (pageHeight - (marginY * 2))) {
        pdf.addImage(imgData, 'JPEG', marginX, marginY, contentWidth, contentHeight);
      } else {
        const scale = (pageHeight - (marginY * 2)) / contentHeight;
        if (scale >= 0.75) {
          pdf.addImage(imgData, 'JPEG', marginX, marginY, contentWidth * scale, contentHeight * scale);
        } else {
          let heightLeft = contentHeight;
          let position = marginY;
          pdf.addImage(imgData, 'JPEG', marginX, position, contentWidth, contentHeight);
          heightLeft -= (pageHeight - (marginY * 2));
          while (heightLeft > 0) {
            position = position - pageHeight;
            pdf.addPage();
            pdf.addImage(imgData, 'JPEG', marginX, position, contentWidth, contentHeight);
            heightLeft -= pageHeight;
          }
        }
      }

      // DIRECT DOWNLOAD: Triggers browser download without opening any print window
      pdf.save(cleanFilename);
      return;
    }

    // Fallback: html2pdf bundle if direct jspdf import is unavailable
    const html2pdf = await loadHtml2Pdf();
    if (html2pdf) {
      const opt = {
        margin: [6, 8, 6, 8],
        filename: cleanFilename,
        image: { type: 'jpeg', quality: 0.98 },
        html2canvas: { scale: 2, useCORS: true, logging: false, windowWidth: 1024, scrollX: 0, scrollY: 0 },
        jsPDF: { unit: 'mm', format: 'a4', orientation: 'portrait' },
        pagebreak: { mode: ['css', 'legacy'] }
      };
      await html2pdf().set(opt).from(container).save();
      if (document.body.contains(container)) {
        document.body.removeChild(container);
      }
      return;
    }

    throw new Error('PDF engine not initialized');
  } catch (err) {
    console.error('PDF direct download failed:', err);
    if (document.body.contains(container)) {
      document.body.removeChild(container);
    }
  }
}


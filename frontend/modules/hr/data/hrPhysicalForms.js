/**
 * Universal safe browser file download helper
 * Uses setTimeout to allow browser thread to complete reading before revoking object URL
 */
export function downloadFile(filename, mimeType, content) {
  try {
    const blob = new Blob([content], { type: mimeType });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.style.display = 'none';
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => {
      try {
        if (document.body.contains(a)) {
          document.body.removeChild(a);
        }
        URL.revokeObjectURL(url);
      } catch (e) {}
    }, 1000);
  } catch (err) {
    console.error('Download failed:', err);
    if (typeof window !== 'undefined') {
      window.alert('Download could not be initiated: ' + (err.message || 'Unknown error'));
    }
  }
}

/**
 * Download Plain Text file (.txt)
 */
export function downloadText(filename, content) {
  const finalName = filename.endsWith('.txt') ? filename : `${filename}.txt`;
  downloadFile(finalName, 'text/plain;charset=utf-8', content);
}

/**
 * Download JSON data file (.json)
 */
export function downloadJSON(filename, data) {
  const finalName = filename.endsWith('.json') ? filename : `${filename}.json`;
  downloadFile(finalName, 'application/json;charset=utf-8', JSON.stringify(data, null, 2));
}

/**
 * Download CSV spreadsheet file (.csv)
 * Prefixed with UTF-8 BOM (\ufeff) so Microsoft Excel opens it seamlessly
 */
export function downloadCSV(filename, headers, rows) {
  const escapeCell = (val) => {
    if (val === null || val === undefined) return '""';
    const str = String(val).replace(/"/g, '""');
    return `"${str}"`;
  };

  const headerLine = headers.map(escapeCell).join(',');
  const rowLines = rows.map(r => r.map(escapeCell).join(','));
  const csvContent = '\ufeff' + [headerLine, ...rowLines].join('\r\n');
  
  const finalName = filename.endsWith('.csv') ? filename : `${filename}.csv`;
  downloadFile(finalName, 'text/csv;charset=utf-8', csvContent);
}

/**
 * Dynamic loader for html2pdf.bundle.min.js
 * First tries local ERP static asset /html2pdf.bundle.min.js, falls back to cdnjs
 */
let html2pdfPromise = null;

export function loadHtml2Pdf() {
  if (typeof window === 'undefined') return Promise.resolve(null);
  if (window.html2pdf) return Promise.resolve(window.html2pdf);
  if (html2pdfPromise) return html2pdfPromise;

  html2pdfPromise = new Promise((resolve, reject) => {
    // 1. Try local bundled script
    const localScript = document.createElement('script');
    localScript.src = '/html2pdf.bundle.min.js';
    localScript.async = true;

    localScript.onload = () => {
      if (window.html2pdf) {
        resolve(window.html2pdf);
      } else {
        tryCdn();
      }
    };

    localScript.onerror = () => {
      tryCdn();
    };

    function tryCdn() {
      const cdnScript = document.createElement('script');
      cdnScript.src = 'https://cdnjs.cloudflare.com/ajax/libs/html2pdf.js/0.10.1/html2pdf.bundle.min.js';
      cdnScript.async = true;
      cdnScript.onload = () => {
        if (window.html2pdf) {
          resolve(window.html2pdf);
        } else {
          reject(new Error('html2pdf library loaded but not found on window.'));
        }
      };
      cdnScript.onerror = (err) => {
        reject(new Error('Failed to load html2pdf script from local and CDN sources: ' + err));
      };
      document.head.appendChild(cdnScript);
    }

    document.head.appendChild(localScript);
  });

  return html2pdfPromise;
}

let pdfLibsPromise = null;
export function getPdfLibs() {
  if (typeof window === 'undefined') return Promise.resolve(null);
  if (pdfLibsPromise) return pdfLibsPromise;

  pdfLibsPromise = Promise.all([
    import('jspdf'),
    import('html2canvas')
  ]).then(([jsPdfMod, html2canvasMod]) => {
    const jsPDF = jsPdfMod.default || jsPdfMod.jsPDF || jsPdfMod;
    const html2canvas = html2canvasMod.default || html2canvasMod;
    return { jsPDF, html2canvas };
  }).catch(err => {
    console.warn('Direct dynamic import of jspdf/html2canvas failed:', err);
    return null;
  });

  return pdfLibsPromise;
}


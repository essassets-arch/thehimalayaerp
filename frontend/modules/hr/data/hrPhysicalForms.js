/**
 * Helper: Resolve Form definition from form object or formNo string
 */
export function getFormDef(formOrCode) {
  if (typeof formOrCode === 'object' && formOrCode !== null && formOrCode.formNo) {
    const base = INITIAL_HR_FORMS.find(f => f.formNo === formOrCode.formNo || f.id === formOrCode.formNo) || {};
    return { ...base, ...formOrCode };
  }
  const code = String(formOrCode || 'HR-F-01');
  const found = INITIAL_HR_FORMS.find(f => f.formNo === code || f.id === code);
  if (found) return found;
  return { formNo: code, title: code, revision: '00', category: 'HR' };
}

